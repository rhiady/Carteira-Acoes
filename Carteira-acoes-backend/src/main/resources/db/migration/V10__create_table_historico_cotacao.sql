CREATE TABLE historico_cotacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    acao_id BIGINT NOT NULL,
    cotacao DECIMAL(19,4) NOT NULL,
    data_hora TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_historico_cotacao_valor CHECK (cotacao > 0),
    CONSTRAINT fk_historico_cotacao_acao FOREIGN KEY (acao_id) REFERENCES acao (id)
);

CREATE INDEX idx_historico_cotacao_acao_data_hora
    ON historico_cotacao (acao_id, data_hora, id);
